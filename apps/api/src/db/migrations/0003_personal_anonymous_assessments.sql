-- users.phone становится НЕОБЯЗАТЕЛЬНЫМ на уровне схемы.
--
-- Раньше: без телефона результат считался и показывался, но НЕ сохранялся
-- (нечего было сравнивать "через месяц", поэтому и хранить анонимную
-- запись казалось незачем).
--
-- Теперь: каждое нажатие "Посчитать" на /personal должно сохраняться —
-- нужно для (а) счётчика "уже прошли анализ" на лендинге, который обязан
-- считать реально ВСЕ случаи, а не только тех, кто оставил телефон, и (b)
-- percentile/peer-выборки (getPeerAssessments), которая теперь опирается на
-- всех, а не только на телефонных пользователей.
--
-- Механизм: для каждой отправки БЕЗ телефона создаётся своя отдельная
-- строка users с phone = NULL (см. createAnonymousUser() в usersRepo.ts) —
-- то есть один анонимный расчёт = один одноразовый user, а не общий
-- "anonymous"-пользователь на всех. UNIQUE(phone) при этом не ломается:
-- в PostgreSQL несколько NULL не считаются дубликатами друг друга при
-- уникальном ограничении. Каждая строка assessments (и, соответственно,
-- каждый расчёт) как и раньше имеет свой уникальный BIGSERIAL id.
ALTER TABLE users ALTER COLUMN phone DROP NOT NULL;
